/**
 * Builds src/data/borders.ts, the land-border graph used by Road Trip.
 *
 * Neighbours are countries whose outlines in countries-low.geojson share border
 * points. The low-detail outlines miss some short borders and invent one, so the
 * result is patched by hand below (checked against a list of land borders).
 *
 * Run: node scripts/build-borders.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const geo = JSON.parse(fs.readFileSync(path.join(root, 'src/assets/geo/countries-low.geojson'), 'utf8'));

/** Natural Earth pieces that are drawn as part of another country (their ISO is -99 or political) */
const MERGE_BY_NAME = {
  Palestine: 'IL', Somaliland: 'SO', 'N. Cyprus': 'CY', 'Siachen Glacier': 'IN',
  'Indian Ocean Ter.': 'AU', 'Ashmore and Cartier Is.': 'AU',
};
/** Not countries for this game (special territories with a land border) */
const SKIP = new Set(['HK', 'MO', 'MF', 'SX']);

/** Real land borders the low-detail outlines miss */
const ADD = [
  ['AF', 'CN'], ['AM', 'IR'], ['BW', 'ZM'], ['DZ', 'EH'], ['FR', 'LU'], ['FR', 'MC'],
  ['HR', 'ME'], ['HU', 'RO'], ['HU', 'RS'], ['LI', 'CH'], ['LT', 'PL'], ['ME', 'RS'], ['TZ', 'UG'],
];
/**
 * Outlines that touch at a corner only, with no real border; and France's border in
 * South America (French Guiana), which would make Europe reachable from the Americas.
 */
const REMOVE = [['NA', 'ZW'], ['FR', 'BR'], ['FR', 'SR']];

const iso = f => MERGE_BY_NAME[f.properties.NAME] ?? f.properties.ISO_A2_EH;
const feats = geo.features.filter(f => !SKIP.has(iso(f)) && iso(f) !== '-99');

const owners = new Map();
feats.forEach(f => {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  polys.forEach(p => p.forEach(ring => ring.forEach(([x, y]) => {
    const k = `${x.toFixed(3)},${y.toFixed(3)}`;
    if (!owners.has(k)) owners.set(k, new Set());
    owners.get(k).add(iso(f));
  })));
});

const adj = new Map();
const link = (a, b) => {
  if (a === b) return;
  if (!adj.has(a)) adj.set(a, new Set());
  if (!adj.has(b)) adj.set(b, new Set());
  adj.get(a).add(b);
  adj.get(b).add(a);
};
owners.forEach(set => set.forEach(a => set.forEach(b => link(a, b))));
ADD.forEach(([a, b]) => link(a, b));
REMOVE.forEach(([a, b]) => {
  adj.get(a)?.delete(b);
  adj.get(b)?.delete(a);
});

const lines = [...adj.keys()]
  .filter(k => adj.get(k).size > 0)
  .sort()
  .map(k => `  ${k}: [${[...adj.get(k)].sort().map(n => `'${n}'`).join(', ')}],`);

/** Territories, dependencies and uninhabited lands that are not offered as guesses */
const NOT_GUESSABLE = new Set(
  'AQ GS IO SH PN AI FK KY BM VG TC MS JE GG IM AX PM WF BL TF NU CK AS GU MP VI PR NC PF AW CW FO GL HM NF'.split(' ')
);
/** Friendlier names for Natural Earth's abbreviated ones */
const RENAME = {
  US: 'United States', CD: 'DR Congo', CG: 'Republic of the Congo', CF: 'Central African Republic',
  DO: 'Dominican Republic', BA: 'Bosnia and Herzegovina', SS: 'South Sudan', GQ: 'Equatorial Guinea',
  EH: 'Western Sahara', SZ: 'Eswatini', VC: 'St Vincent and the Grenadines', KN: 'St Kitts and Nevis',
  LC: 'St Lucia', SB: 'Solomon Islands', MH: 'Marshall Islands', CI: "Côte d'Ivoire", ST: 'São Tomé and Príncipe',
  AG: 'Antigua and Barbuda', TR: 'Turkey', CZ: 'Czechia', MK: 'North Macedonia', TL: 'Timor-Leste',
};
const names = new Map();
for (const f of geo.features) {
  const code = iso(f);
  if (code === '-99' || SKIP.has(code) || NOT_GUESSABLE.has(code) || Object.hasOwn(MERGE_BY_NAME, f.properties.NAME)) continue;
  names.set(code, RENAME[code] ?? f.properties.NAME);
}
const nameLines = [...names.entries()]
  .sort((a, b) => a[1].localeCompare(b[1]))
  .map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`);

const out = `// Generated by scripts/build-borders.mjs; edit the script, not this file.
/** Land borders between countries (ISO 3166-1 alpha-2). Countries with none are left out. */
export const BORDERS: Record<string, readonly string[]> = {
${lines.join('\n')}
};

/** Natural Earth pieces (by name) drawn as part of another country */
export const MERGED_INTO: Record<string, string> = ${JSON.stringify(MERGE_BY_NAME)};

/** Every country a player can name, with its display name */
export const COUNTRY_NAMES: Record<string, string> = {
${nameLines.join('\n')}
};
`;
fs.writeFileSync(path.join(root, 'src/data/borders.ts'), out);
console.log(`${lines.length} countries with land borders`);
